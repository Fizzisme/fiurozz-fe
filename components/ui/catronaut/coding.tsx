export default function CatronautCoding({ scale = 5, className }: CodingPetProps) {
    const canvasRef = useRef<HTMLCanvasElement>(null);
    const rafRef = useRef<number>(0);

    useEffect(() => {
        const canvas = canvasRef.current;
        if (!canvas) return;
        const ctx = canvas.getContext('2d');
        if (!ctx) return;
        ctx.imageSmoothingEnabled = false;

        const cat = themedSprite(MAIN_GRID, PALETTE);
        // the heart bubble already reads on both grounds (light outline, orange fill)
        const heart = themedSprite(HEART_GRID, PALETTE).light;
        const reduced = prefersReducedMotion();
        const HEART_CYCLE = 260;

        let t = 0;

        const render = () => {
            let heartY = 0;
            let heartAlpha = 1;

            if (!reduced) {
                const hp = (t % HEART_CYCLE) / HEART_CYCLE;

                if (hp < 0.12) {
                    heartAlpha = hp / 0.12;
                } else if (hp < 0.75) {
                    heartY = -Math.round(((hp - 0.12) / 0.63) * 4);
                } else {
                    heartAlpha = 1 - (hp - 0.75) / 0.25;
                    heartY = -4;
                }
            }

            ctx.clearRect(0, 0, canvas.width, canvas.height);
            ctx.drawImage(isDarkTheme() ? cat.dark : cat.light, 0, 0);

            ctx.save();
            ctx.globalAlpha = heartAlpha;
            ctx.drawImage(heart, HX0, HY0 + heartY);
            ctx.restore();
        };

        if (reduced) {
            render();
            return;
        }

        const frame = () => {
            t += 1;
            render();
            rafRef.current = requestAnimationFrame(frame);
        };

        frame();
        return () => cancelAnimationFrame(rafRef.current);
    }, []);

    return (
        <canvas
            ref={canvasRef}
            width={G}
            height={G}
            className={className}
            style={{
                width: G * scale,
                height: G * scale,
                maxWidth: 'none',
                maxHeight: 'none',
                display: 'block',
                flexShrink: 0,
                boxSizing: 'content-box',
                imageRendering: 'pixelated',
            }}
        />
    );
}
