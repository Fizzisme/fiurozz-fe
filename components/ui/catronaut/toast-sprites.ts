/** One point of the loading orbit; points marked front are drawn over the helmet. */
export interface OrbitPoint {
    x: number;
    y: number;
    front: boolean;
}

export const ORBIT_STEPS = 220;

/** A tilted ellipse around the helmet, sampled into pixel positions (duplicates removed). */
export function buildOrbit(o: typeof LOADING_LAYOUT.orbit): OrbitPoint[] {
    const points: OrbitPoint[] = [];
    let last = '';
    for (let k = 0; k < ORBIT_STEPS; k++) {
        const a = (k / ORBIT_STEPS) * Math.PI * 2;
        const ex = Math.cos(a) * o.rx;
        const ey = Math.sin(a) * o.ry;
        const x = Math.round(o.cx + ex * Math.cos(o.tilt) - ey * Math.sin(o.tilt) - 0.5);
        const y = Math.round(o.cy + ex * Math.sin(o.tilt) + ey * Math.cos(o.tilt) - 0.5);
        const key = x + ',' + y;
        if (key === last) continue;
        last = key;
        points.push({ x, y, front: Math.sin(a) > 0 });
    }
    return points;
}

/** Paints a palette grid at (offX, offY); 0 cells stay transparent. */
export function drawGrid(ctx: CanvasRenderingContext2D, grid: number[][], offX: number, offY: number) {
    for (let y = 0; y < grid.length; y++) {
        const row = grid[y];
        for (let x = 0; x < row.length; x++) {
            const color = PALETTE[row[x]];
            if (!color) continue;
            ctx.fillStyle = color;
            ctx.fillRect(x + offX, y + offY, 1, 1);
        }
    }
}

/** Renders a grid once into an offscreen canvas, so a frame can drawImage it instead. */
export function prerender(grid: number[][]): HTMLCanvasElement {
    const canvas = document.createElement('canvas');
    canvas.width = grid[0].length;
    canvas.height = grid.length;
    const ctx = canvas.getContext('2d');
    if (ctx) drawGrid(ctx, grid, 0, 0);
    return canvas;
}

/** The soft floor shadow, same treatment as CatronautIdle. */
export function drawShadow(ctx: CanvasRenderingContext2D, scaleFactor = 1) {
    ctx.fillStyle = document.documentElement.classList.contains('dark') ? 'rgba(0,0,0,0.35)' : 'rgba(20,20,20,0.16)';
    ctx.beginPath();
    ctx.ellipse(SHADOW.cx, SHADOW.cy, SHADOW.rx * scaleFactor, SHADOW.ry * scaleFactor, 0, 0, Math.PI * 2);
    ctx.fill();
}

